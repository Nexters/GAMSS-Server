package com.nexters.gamss.notification.domain

/**
 * 알림 한 건이 어떻게 끝났는지.
 *
 * 성공, 실패 둘로 두지 않는다. [NO_DEVICE] 는 알림을 끈 회원이라 정상이고 [SKIPPED] 도 정상인데,
 * 셋을 뭉치면 백오피스에서 '안 갔다'로만 보여 대응할 것과 아닌 것이 구분되지 않는다.
 */
enum class NotificationOutcome {
    /** FCM 이 성공을 돌려줬다. */
    SENT,

    /** 보낼 기기가 없었다. 알림을 껐거나 앱을 지운 회원이라 실패가 아니다. */
    NO_DEVICE,

    /** FCM 이 실패를 돌려줬다. */
    FAILED,

    /**
     * 이 방 때문에 보내지는 않았다. 같은 회원의 다른 방으로 이미 같은 알림이 나간 경우다.
     *
     * 이 값이 필요한 이유는 "대상이었지만 안 보냈다"와 "애초에 대상이 아니었다"가 다르기 때문이다.
     * 후자는 행 자체가 없다.
     */
    SKIPPED,

    /**
     * 배치가 대상으로 뽑아 처리하려 했지만, 그사이 다른 경로(주로 사용자의 수동 종료+생성)로 이미
     * 끝나 있었다. 05:00 카드 알림([com.nexters.gamss.card.service.DailyAutoCardScheduler])에서만
     * 쓰인다.
     *
     * 이 값이 없으면 "배치가 실제로 이 방을 봤는데 할 일이 없었다"와 "배치가 이 방을 애초에 보지도
     * 않았다"(행 자체가 없음)가 구분되지 않는다.
     */
    ALREADY_HANDLED,
}
