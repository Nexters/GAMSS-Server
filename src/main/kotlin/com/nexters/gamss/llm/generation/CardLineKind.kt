package com.nexters.gamss.llm.generation

/**
 * 카드 한 줄 생성기가 입력을 보고 내린 판정. 카드의 한 줄을 누가 말하는지가 여기서 갈린다.
 *
 * 판정을 따로 받는 이유는 LLM에게 "쓸 사건이 없다"고 답할 길을 열어 두기 위해서다. 입력이 무엇이든
 * 사건 하나를 고르게 하면, 알아볼 수 있는 내용이 없는 대화(자모 나열, 키보드 연타)에서도 LLM이 없는
 * 사건을 지어낸다.
 */
enum class CardLineKind {
    /** 유저 시점의 하루 기록으로 쓸 수 있다. 사건 없이 기분이나 상태만 드러나도 여기다. */
    EVENT,

    /**
     * 그날 있었던 일도, 기분이나 상태도 알 수 없다(자모 나열, 인사, 'ㅇㅋ' 같은 짧은 말). 사건을 지어내는 대신 유저가
     * 보낸 첫 메시지를 그대로 한 줄로 남긴다([com.nexters.gamss.card.service.CardService]).
     *
     * 애매한 입력도 기분이나 상태가 드러나지 않으면 여기로 온다. EVENT로 보내면 LLM이 없는 사건이나 기분으로 한 줄을
     * 채우지만, 첫 메시지는 유저가 친 말이라 지어낸 것이 없다.
     */
    NONSENSE,
}
